(async function () {
    let checks = 0;
    const assert = (condition, message) => { checks++; if (!condition) throw new Error(message); };
    const settle = async () => { for (let i = 0; i < 12; i++) await Promise.resolve(); };
    let result;
    try {
        await settle();
        const button = id => document.getElementById(id).click();
        const inputs = name => Array.from(document.querySelectorAll('#thresholds .' + name));
        const supportLink = document.querySelector('.support-note a');
        assert(supportLink.href === 'mailto:chesstimer@cimach.eu', 'Footer provides the bug-report email link');
        assert(document.getElementById('gameStatus').textContent.includes('Clock detected'), 'Status messaging');
        button('openSettings');
        assert(!document.getElementById('playerView').hidden && document.getElementById('alertsView').hidden, 'Open player settings');
        document.getElementById('username').value = 'alice';
        document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
        assert(!document.getElementById('alertsView').hidden && document.getElementById('username').value === 'alice', 'Back preserves unsaved player settings');
        const presetSelect = document.getElementById('preset');
        presetSelect.value = 'default-30-15-5';
        presetSelect.dispatchEvent(new Event('change', { bubbles: true }));
        assert(inputs('threshold').length === 3 && window.__writes.length === 0, 'Preset needs explicit save');
        button('save'); await settle();
        assert(window.__writes.length === 1 && window.__writes[0].chessAlertSettings.alertSettings[0].threshold === 30, 'Save preset');
        assert(window.__writes[0].chessAlertSettings.username === 'alice', 'Save includes settings from the second view');
        const symbols = Array.from(document.querySelectorAll('.symbol'));
        await document.fonts.ready;
        assert(document.fonts.check('20px "Material Symbols Outlined"') && symbols.every(s => s.getAttribute('aria-hidden') === 'true'), 'Bundled Google symbols load and remain decorative');
        const measureGlyph = name => {
            const glyph = document.querySelector('#editPreset .symbol').cloneNode(true);
            glyph.textContent = name; glyph.style.width = 'auto'; document.body.append(glyph);
            const width = glyph.getBoundingClientRect().width; glyph.remove(); return width;
        };
        assert(measureGlyph('edit') < 26 && measureGlyph('check') < 26, 'Google Fonts subset contains the edit and check ligatures');
        button('addButton');
        assert(inputs('threshold').map(input => input.valueAsNumber).join(',') === '30,15,10,5', 'Adding keeps alerts sorted from longest to shortest');
        const addedThreshold = inputs('threshold').find(input => input.valueAsNumber === 10);
        assert(document.activeElement === addedThreshold, 'New alert threshold receives focus');
        addedThreshold.value = '40'; addedThreshold.dispatchEvent(new Event('input', { bubbles: true }));
        addedThreshold.dispatchEvent(new Event('change', { bubbles: true }));
        assert(inputs('threshold').map(input => input.valueAsNumber).join(',') === '40,30,15,5', 'Editing a threshold re-sorts alerts immediately');
        addedThreshold.value = '5'; addedThreshold.dispatchEvent(new Event('input', { bubbles: true }));
        addedThreshold.dispatchEvent(new Event('change', { bubbles: true }));
        button('save'); await settle();
        assert(window.__writes.length === 1, 'Duplicate is rejected');
        addedThreshold.value = '10'; addedThreshold.dispatchEvent(new Event('input', { bubbles: true }));
        addedThreshold.dispatchEvent(new Event('change', { bubbles: true }));
        inputs('amount').at(-1).value = '1.5';
        button('save'); await settle();
        assert(window.__writes.length === 1, 'Fractional amount is rejected');
        document.querySelector('#thresholds tr:last-child .remove').click();
        assert(inputs('threshold').length === 3, 'Remove individual row');
        button('clear'); await settle();
        assert(inputs('threshold').length === 0 && !document.getElementById('enabled').checked, 'Clear updates popup');
        assert(!document.getElementById('emptyState').hidden && document.getElementById('enabledLabel').textContent === 'OFF', 'Empty state and toggle reflect clear');
        assert(window.__writes.at(-1).chessAlertSettings.enabled === false, 'Clear persists disabled tombstone');
        button('addButton');
        inputs('threshold')[0].value = '0';
        button('save'); await settle();
        assert(window.__writes.length === 2, 'Out-of-range threshold is rejected');
        button('openSettings'); button('save'); await settle();
        assert(!document.getElementById('alertsView').hidden && window.__writes.length === 2, 'Invalid hidden alert is revealed when saving from settings');
        result = `PASS ${checks} popup checks`;
    } catch (error) { result = `FAIL ${error.stack}`; }
    const output = document.createElement('pre');
    output.id = 'test-result'; output.textContent = result; document.body.append(output);
    void fetch('/__result', { method: 'POST', body: result });
})();
